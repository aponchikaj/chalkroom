#!/usr/bin/env node
/*
  Build the burned-in subtitle layer and the SRT from script.json.

    node tools/build-subs.mjs        (or: npm run subs)

  Writes:
    compositions/subtitles.html   full-length composition mounted on top of the scenes
    subtitles.ka.srt              same cues as SubRip

  Retiming after the voice is recorded: edit the cue start/end in script.json,
  run this again, then re-snapshot. Never hand-edit the generated files.
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const script = JSON.parse(fs.readFileSync(path.join(root, 'script.json'), 'utf8'));
const duration = script.duration;
const cues = script.cues.slice().sort((a, b) => a.start - b.start);

// sanity: ordered, non-overlapping, inside the film
const problems = [];
cues.forEach((c, i) => {
  if (!(c.end > c.start)) problems.push(`${c.id}: end <= start`);
  if (c.start < 0 || c.end > duration) problems.push(`${c.id}: outside 0..${duration}`);
  if (i > 0 && c.start < cues[i - 1].end) problems.push(`${c.id}: overlaps ${cues[i - 1].id}`);
  if (Array.from(c.text).length > 110) problems.push(`${c.id}: ${Array.from(c.text).length} chars, may exceed two lines`);
});
if (problems.length) console.warn('warnings:\n  ' + problems.join('\n  '));

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const fix = (n) => Number(n.toFixed(3));

const cueHtml = cues
  .map((c) => `    <div class="sub-cue" data-layout-allow-caption-zone id="sub-${c.id}" data-in="${fix(c.start)}" data-out="${fix(c.end)}"><span>${esc(c.text)}</span></div>`)
  .join('\n');

const html = `<!-- GENERATED by tools/build-subs.mjs from script.json. Do not edit; edit script.json and re-run. -->
<template id="subtitles-template">
  <div data-composition-id="subtitles" data-width="1920" data-height="1080" data-duration="${duration}">
    <link rel="stylesheet" href="../assets/chalk.css" />
    <script src="../assets/vendor/gsap.min.js"></script>
    <script src="../assets/kit.js"></script>
    <style>
      .sub-band { position: absolute; left: 0; right: 0; bottom: 54px; height: 0; }
      /* centred by left/right insets, never by transform (GSAP owns transform) */
      .sub-cue { position: absolute; left: 260px; right: 260px; bottom: 0; text-align: center; visibility: hidden; }
      .sub-cue span {
        display: inline-block; max-width: 1400px; padding: 12px 30px 14px;
        background: rgba(251, 248, 241, 0.94); border-top: 1.5px solid var(--ink); border-radius: 3px;
        box-shadow: var(--shadow-leaf);
        font-family: 'Noto Serif Georgian', 'Source Serif 4', serif; font-size: 40px; font-weight: 500;
        line-height: 1.32; color: var(--ink); text-wrap: balance;
      }
    </style>
    <div class="sub-band">
${cueHtml}
    </div>
    <script>
      (function () {
        const S = Kit.scope('subtitles');
        const tl = gsap.timeline({ paused: true });
        S.qa('.sub-cue').forEach(function (el) {
          const tin = parseFloat(el.dataset.in);
          const tout = parseFloat(el.dataset.out);
          Kit.stepIn(tl, el, tin);
          Kit.stepOut(tl, el, tout - 0.066, { y: 0 });
        });
        tl.set({}, {}, ${duration});
        window.__timelines = window.__timelines || {};
        window.__timelines['subtitles'] = tl;
      })();
    </script>
  </div>
</template>
`;
fs.writeFileSync(path.join(root, 'compositions', 'subtitles.html'), html);

const srtTime = (s) => {
  const ms = Math.round(s * 1000);
  const h = Math.floor(ms / 3600000);
  const m = Math.floor((ms % 3600000) / 60000);
  const sec = Math.floor((ms % 60000) / 1000);
  const r = ms % 1000;
  const p = (n, w = 2) => String(n).padStart(w, '0');
  return `${p(h)}:${p(m)}:${p(sec)},${p(r, 3)}`;
};
const srt = cues.map((c, i) => `${i + 1}\n${srtTime(c.start)} --> ${srtTime(c.end)}\n${c.text}\n`).join('\n');
fs.writeFileSync(path.join(root, 'subtitles.ka.srt'), srt);

console.log(`subtitles: ${cues.length} cues -> compositions/subtitles.html, subtitles.ka.srt`);
